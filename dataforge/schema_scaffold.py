"""Scaffold a DECLARED premise draft from inferred candidates.

**The gap this closes.** Since C4 (``PRODUCT.md`` §1.5) a mined constraint confers no write
authority, so the only path from a dirty table to a proven repair is a *declared* schema
passed with ``--schema``. There was no command that produced one. ``schema_inference.py``
already computes column types, regex candidates, domain bounds, uniqueness and functional
dependencies for ``profile --json``, but nothing shaped them into a file a human could
review, edit and own -- so the operator faced a blank page, and the product's only measured
end-to-end correction result was reachable only by someone who already knew the format.

**Why the draft is deliberately inert.** The obvious implementation -- emit the inferred
types as declarations -- would be a mined premise with extra steps, and would hand back
exactly the write authority C4 removed on measured grounds (no in-table quality measure
transfers across tables; the best of four discards 16 of 143 hand-annotated true
dependencies on an unseen table). So:

* every column is declared ``string``, which is **non-discriminating**. Since 2026-08-25 a
  declared type must be able to reject something before it confers proof
  (``PRODUCT.md`` §1.2), so an unedited draft is provably incapable of authorising a write.
  That is not a convention this module enforces by hand -- it falls out of the entailment
  strength rule already in the verifier;
* every inferred candidate is emitted **commented out**, with the evidence that produced it;
* uncommenting one is the operator's act of authorship, and the file records that plainly.

The result teaches the product's central concept instead of hiding it: the operator can see
precisely which declarations would grant authority over which columns, and must choose them.

``tests/unit/test_schema_scaffold.py`` asserts an unedited draft writes zero cells through
the real pipeline. If that test ever fails, this module has started conferring authority and
the C4 guarantee is gone.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Final

if TYPE_CHECKING:
    from dataforge.schema_inference import SchemaInferenceResult

#: Declared for every column in a fresh draft. Non-discriminating on purpose -- see module
#: docstring. Changing this to an inferred type would silently restore mined write authority.
INERT_TYPE: Final[str] = "string"

_HEADER: Final[str] = """\
# DataForge declared-premise draft
#
# Generated by `dataforge schema init` from {row_count} row(s) of {source}.
# NOTHING IN THIS FILE GRANTS WRITE AUTHORITY YET, AND THAT IS DELIBERATE.
#
# Every column below is declared `{inert}`. A `{inert}` declaration cannot reject any CSV
# value -- every cell is already a string -- so it confers no proof and DataForge will not
# auto-apply a repair on its strength. Running `dataforge repair --schema <this file>`
# unedited will therefore write ZERO cells, by construction rather than by convention.
#
# The commented blocks are what DataForge OBSERVED in your data, with the evidence for each.
# They are suggestions, not declarations: an inferred constraint is a guess about your
# domain, and DataForge has measured that such guesses do not transfer between tables.
#
# TO EARN PROVEN WRITES: replace a `{inert}` with a real type, or uncomment a constraint you
# know to be true of your data. That act -- you asserting what is true -- is what turns a
# guess into a premise. Tighten only what you are willing to stand behind.
#
# A functional dependency is the strongest thing you can declare here and the one to be most
# careful with: `fd_violation` is one of only two detectors permitted to write, so a FALSE
# dependency will overwrite correct values. Declaring `ZipCode -> HospitalName` was measured
# corrupting 23 already-correct cells, because a zip code does not determine a hospital name.
"""


def _quote(value: str) -> str:
    """Emit a YAML double-quoted scalar, escaping what YAML requires.

    Every column name goes through this, and the reason is measured rather than defensive.
    An unquoted name was mishandled for 7 of 12 hostile inputs on 2026-09-12: ``a: b`` and
    ``tab\\tsep`` and ``*star`` and ``{brace}`` raised parse errors, while ``yes`` became the
    key ``True``, ``null`` became ``None``, ``123`` became an integer and ``- dash`` turned the
    whole ``columns`` mapping into a list.

    The silent coercions are the dangerous half. A CSV with a year column named ``2023`` or a
    flag column named ``yes`` produced a draft that PARSED, looked correct, and keyed the
    declaration to something that is not the column -- so a premise the operator believed they
    had authored would quietly apply to nothing. Found by an independent reviewer attacking
    this function, not by its author.
    """
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    for raw, digraph in (("\n", "\\n"), ("\r", "\\r"), ("\t", "\\t")):
        escaped = escaped.replace(raw, digraph)
    return f'"{escaped}"'


def _candidate_comment(candidate: object) -> list[str]:
    """Render one inferred candidate as commented YAML with its evidence.

    Returns an empty list for a candidate kind this scaffold has no declaration shape for,
    rather than inventing one -- an unrecognised candidate is dropped from the *suggestions*,
    never silently turned into a declaration.
    """
    kind = getattr(candidate, "kind", None)
    columns = list(getattr(candidate, "columns", ()) or ())
    evidence = getattr(candidate, "evidence", None) or "no evidence recorded"
    confidence = getattr(candidate, "confidence", None)
    tested = getattr(candidate, "tested_confidence", None)

    detail = f"#   evidence: {evidence}"
    if confidence is not None:
        detail += f" (confidence {confidence:.4f}"
        if tested is not None:
            detail += f", tested {tested:.4f}"
        detail += ")"

    if kind == "column_type" and columns:
        inferred = getattr(candidate, "inferred_type", None)
        if not inferred:
            return []
        return [
            f"# {_quote(columns[0])}: {inferred}"
            "   <-- tighten `columns:` above to this to gain authority",
            detail,
        ]

    if kind == "regex" and columns:
        pattern = getattr(candidate, "pattern", None)
        if not pattern:
            return []
        return [
            "# - column: " + _quote(columns[0]),
            f"#   pattern: {_quote(pattern)}",
            detail,
        ]

    if kind == "domain_bound" and columns:
        low = getattr(candidate, "min_value", None)
        high = getattr(candidate, "max_value", None)
        if low is None and high is None:
            return []
        return [
            "# - column: " + _quote(columns[0]),
            f"#   min_value: {low}",
            f"#   max_value: {high}",
            detail,
        ]

    if kind in {"unique", "uniqueness"} and columns:
        return [f"# - {_quote(columns[0])}", detail]

    if kind in {"functional_dependency", "fd"} and columns:
        dependent = getattr(candidate, "dependent", None)
        if not dependent:
            return []
        determinant = ", ".join(_quote(column) for column in columns)
        return [
            f"# - determinant: [{determinant}]",
            f"#   dependent: {_quote(dependent)}",
            detail,
            "#   WARNING: a false dependency here overwrites correct values.",
        ]

    return []


def _section(title: str, key: str, blocks: list[list[str]]) -> list[str]:
    """Render a commented YAML section, or a note that nothing was observed."""
    lines = ["", f"# --- {title} ---"]
    if not blocks:
        lines.append("# (none observed in this table)")
        return lines
    lines.append(f"# {key}:")
    for block in blocks:
        lines.extend(block)
    return lines


def build_schema_draft(
    inference: SchemaInferenceResult,
    *,
    source: str,
) -> str:
    """Build the text of a declared-premise draft.

    Args:
        inference: Result of :func:`dataforge.schema_inference.infer_schema`.
        source: Path or identifier of the table, recorded in the header.

    Returns:
        YAML text. Parsing it yields a schema whose every column is
        :data:`INERT_TYPE`, so it authorises no writes until a human edits it.
    """
    columns = dict(getattr(inference, "columns", {}) or {})
    row_count = getattr(inference, "row_count", 0)
    candidates = list(getattr(inference, "candidates", ()) or ())

    lines = [_HEADER.format(row_count=row_count, source=source, inert=INERT_TYPE)]

    lines.append("columns:")
    if columns:
        for name in columns:
            lines.append(f"  {_quote(name)}: {INERT_TYPE}")
    else:
        lines.append("  {}")

    by_kind: dict[str, list[list[str]]] = {}
    for candidate in candidates:
        block = _candidate_comment(candidate)
        if block:
            by_kind.setdefault(str(getattr(candidate, "kind", "other")), []).append(block)

    lines.extend(_section("Observed column types", "columns", by_kind.get("column_type", [])))
    lines.extend(_section("Observed value patterns", "regex_constraints", by_kind.get("regex", [])))
    lines.extend(
        _section("Observed numeric ranges", "domain_bounds", by_kind.get("domain_bound", []))
    )
    unique_blocks = by_kind.get("unique", []) + by_kind.get("uniqueness", [])
    lines.extend(_section("Observed unique columns", "unique_columns", unique_blocks))
    fd_blocks = by_kind.get("functional_dependency", []) + by_kind.get("fd", [])
    lines.extend(_section("Observed functional dependencies", "functional_dependencies", fd_blocks))

    lines.append("")
    return "\n".join(lines) + "\n"
